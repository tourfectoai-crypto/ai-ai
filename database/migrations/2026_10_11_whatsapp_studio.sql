CREATE TABLE IF NOT EXISTS wa_studio_media (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL, website_id BIGINT UNSIGNED NOT NULL,
 connection_hash CHAR(64) NOT NULL, media_id VARCHAR(64) NOT NULL,
 example_handle TEXT NULL, mime VARCHAR(80) NOT NULL, byte_size INT UNSIGNED NOT NULL,
 file_key CHAR(48) NOT NULL, original_name VARCHAR(190) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX owner_media(user_id,website_id,media_id), UNIQUE KEY file_key(file_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS wa_signup_forms (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL, website_id BIGINT UNSIGNED NOT NULL,
 token CHAR(64) NOT NULL, title VARCHAR(190) NOT NULL,
 language VARCHAR(12) NOT NULL DEFAULT 'en', privacy_url VARCHAR(1000) NOT NULL,
 active TINYINT NOT NULL DEFAULT 1, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY token(token), INDEX owner(user_id,website_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS wa_campaign_links (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL, website_id BIGINT UNSIGNED NOT NULL,
 campaign_id BIGINT UNSIGNED NOT NULL, generated_website_id BIGINT UNSIGNED NULL, token CHAR(64) NOT NULL,
 target_url VARCHAR(2000) NOT NULL, clicks BIGINT UNSIGNED NOT NULL DEFAULT 0, last_clicked_at DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY token(token), INDEX campaign(campaign_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS wa_booking_attribution (
 booking_id BIGINT UNSIGNED NOT NULL PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL, website_id BIGINT UNSIGNED NOT NULL,
 campaign_id BIGINT UNSIGNED NOT NULL, link_id BIGINT UNSIGNED NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX campaign(campaign_id,user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS wa_campaign_experiments (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL, website_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(190) NOT NULL, state VARCHAR(20) NOT NULL DEFAULT 'draft', campaign_a BIGINT UNSIGNED NOT NULL,
 campaign_b BIGINT UNSIGNED NOT NULL, split_json LONGTEXT NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX owner(user_id,website_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS wa_signup_requests (
 token CHAR(64) NOT NULL PRIMARY KEY, form_id BIGINT UNSIGNED NOT NULL,
 user_id BIGINT UNSIGNED NOT NULL, website_id BIGINT UNSIGNED NOT NULL,
 phone VARCHAR(15) NOT NULL, name VARCHAR(190) NOT NULL, language VARCHAR(12) NOT NULL,
 evidence VARCHAR(500) NOT NULL, expires_at DATETIME NOT NULL, confirmed_at DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX expires(expires_at), INDEX owner_phone(user_id,website_id,phone)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS wa_flow_responses (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL, website_id BIGINT UNSIGNED NOT NULL,
 phone VARCHAR(15) NOT NULL, wamid VARCHAR(255) NOT NULL, recipient_id BIGINT UNSIGNED NULL,
 response_enc LONGTEXT NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY provider_message(user_id,website_id,wamid), INDEX owner(user_id,website_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
