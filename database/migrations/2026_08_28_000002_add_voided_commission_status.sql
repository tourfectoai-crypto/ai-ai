-- إضافة قيمة 'voided' إلى ENUM حالة عمولة الوكالة (agency_commissions.status):
--   pending → مستحقة ولم تُدفع بعد (تُلغى تلقائيًا عند إلغاء الحجز).
--   paid    → مدفوعة فعلًا (لا تُغيّر تلقائيًا أبدًا - استرداد يدوي).
--   voided  → أُلغي الحجز قبل دفع العمولة (قيمة جديدة تُحفظ بدل الحذف
--             للاحتفاظ بالسجل المالي كاملًا).
--
-- Idempotent: إعادة تشغيل MODIFY COLUMN على نفس التعريف لا تغيّر شيئًا
-- والعمليات الحالية (pending/paid) تُحفظ كما هي.
-- ============================================================

ALTER TABLE `agency_commissions`
    MODIFY COLUMN `status` ENUM('pending','paid','voided') NOT NULL DEFAULT 'pending'
        COMMENT 'pending (مستحقة) / paid (مدفوعة يدويًا) / voided (مُلغاة بعد إلغاء الحجز)';
